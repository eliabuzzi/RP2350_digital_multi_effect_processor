import micropython

# PICCOLO MODULO PER GENERARE UN EVENTO E PROGRAMMARE IL CORE 1 PER RESTARE IN ATTESA DI QUELL'EVENTO
# PERMETTE DI SFRUTTARE LE ISTRUZIONI ARM/THUMB DIRETTAMENTE SENZA MODIFICARE IL FIRMWARE

# data -> ACCETTA UNA DIMENSIONE IN BYTE PER CIASCUN VALORE CHE GLI STIAMO PASSANDO

# CODICI OPTOCODE PER LE ISTRUZIONI THUMB
# 0xBF40 : SEND EVENT
# 0xBF20: WAIT FOR EVENT (NOTA: SE IL REGISTRO INTERNO È GIÀ IMPOSTATO NON ADDORMENTA IL CORE, WFE CONSUMA IL REGISTRO E VA AVANTI)
# 0xF3BF 0x8F5F: DATA MEMORY BARRIER, SHAREABLE/FULL SYSTEM DOMAIN

# NOTA: LE BARRIERE NON SONO OBBLIGATORIE, SONO STATE MESSE PER EVITARE CHE LO SCHEDULER RIORGANIZZI GLI ACCESSI IN MEMORIA E GARANTIRE CONSISTENZA
# AD ESEMPIO NON VOGLIO CHE IL CORE 1 SIA RISVEGLIATO PRIMA CHE IL DMA ABBIA AGGIORNATO L'INDICE GLOBALE DEI BLOCCHI

# SEV (SEND-EVENT): INVIA UN EVENTO AI DUE CORE DEL PROCESSORE
# DMB SY (DATA MEMORY BARRIER, SHAREABLE/FULL SYSTEM): ORDINA GLI ACCESSI ALLA MEMORIA PRIMA DELLA NOTIFICA

@micropython.asm_thumb
def send_event():
    data(2, 0xF3BF, 0x8F5F)         # DMB SY
    data(2, 0xBF40)                 # SEV

# WFE (WAIT FOR EVENT): ATTENDE UN EVENTO
# DOPO IL RISVEGLIO LA BARRIERA ORDINA GLI ACCESSI IN MEMORIA PRIMA CHE PYTHON RICONTROLLI L'INDICE CONDIVISO DEL DMA

@micropython.asm_thumb
def wait_event():
    data(2, 0xBF20)                 # WFE
    data(2, 0xF3BF, 0x8F5F)         # DMB SY