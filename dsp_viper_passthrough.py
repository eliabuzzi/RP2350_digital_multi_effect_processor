import micropython

# CODICE PER IL PASS-THROUGH TRAMITE VIPER
# IN QUESTO CODICE SUPER SEMPLICE NON HO BISOGNO DI CONFIGURAZIONI, MEMORIE O ALTRE COSE STRANE

@micropython.viper

def dsp_viper_bypass(block_index: int):
    # NOTA: block_index -> INDICE LOCALE

    # DEFINISCO GLI INDIRIZZI BASE DEI BUFFER (TRADOTTI IN ARM DIRETTAMENTE IN FASE DI COMPILAZIONE, NON VENGONO RIALLOCATE IN RUN-TIME)
    BASE_IN = ptr32(0x2006C000)         # BASE PER IL PUNTATORE DI LETTURA (DMA IN -> BUFFER_RX)
    BASE_OUT = ptr32(0x20074000)        # BASE PER IL PUNTATORE DI SCRITTURA (BUFFER_TX -> DMA OUT)

    block_size = 64       # DIMENSIONE DEL BLOCCO (IN PAROLE DA 4 BYTE)

    # CALCOLO DELL'OFFSET GLOBALE INTERNO AL BUFFER (IDENTICO SIA PER LETTURA CHE PER SCRITTURA)
    offset = block_index * block_size           # POTRANNO ESSERE GESTITI CON GLI SHIFT

    # COPIA DIRETTA DEI CAMPIONI (PASS-THROUGH)
    # NOTA: IL DAC RIMUOVE LA TRAMA I2S NATIVAMENTE

    for i in range(block_size):
        
        # INDICE GLOBALE
        global_index = offset + i

        # LEGGE IL CAMPIONE DAL BUFFER IN RAM
        sample_raw = int(BASE_IN[global_index])

        # SCRIVE IL CAMPIO NELL'ALTRO BUFFER
        BASE_OUT[global_index] = sample_raw
