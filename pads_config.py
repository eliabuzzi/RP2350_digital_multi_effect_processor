from machine import mem32

# CONFIGURAZIONE HARDWARE PADS: IMPOSTO MINIMO SLEW RATE / DRIVECURRENT, DOVREBBE AIUTARE A DIMINUIRE I "RIMBALZI" NELLE LINEE DEL CLOCK
# OGNI GPIO HA UN REGISTRO DA 32 BIT A ESSO ASSOCIATO, I FLAG BIT A BIT DELLA PARTE LSB SONO
# 0: SLEW RATE (1=FAST, 0=SLOW), 1: TRIGGER DI SCHMITT (1=ON, 0=OFF), 2/3 PER PULL DOWN/UP, 4 e 5 DRIVE STRENGHT (00 = 2mA), 6 e 7 ...

PADS_BANK0_BASE = 0x40038000        # INDIRIZZO BASE DEL REGISTRO HARDWARE PER I PAD
PAD_OFFSETS = [0x0C, 0x10, 0x14]    # IND. PAD = BASE + 0x04 + N_GPIO * 0x04

PIO_MASK = 0xFFFFFFCE               # MASCHERA BITWISE PER AZZERARE I BIT 0, 4 e 5 DELLE RISPETTIVE GPIO

# NOTA: NON ESISTONO MACRO IN MICROPYTHON
def pad_configuration():

    for offset in PAD_OFFSETS:

        reg_addr = PADS_BANK0_BASE + offset # PUNTA AL REGISTRO DI OGNI GPIO DA MODIFICARE

        # OPERAZIONE READ-MODIFY-WRITE
        current_val = mem32[reg_addr]   # PUNTA AL REGISTRO IN MODO SICURO (PER EVITARE DI MODIFICARE FLAG SBAGLIATI E SCIOPPARE TUTTO)
        #print(f"vecchio valore: 0x{current_val:08X} - registro puntato: 0x{reg_addr:08X}")
        
        new_val = current_val & PIO_MASK
        #print(f"nuovo valore: 0x{new_val:08X}")

        mem32[reg_addr] = new_val

    print("PAD HARDWARE CONFIGURATI!\n")