# CODICE PYTHON PER GESTIRE LE SCRITTURE DELLA MAILBOX IN RAM, QUESTO MODULO GESTISCE TUTTO QUANTO IN AUTONOMIA

# CONFIGURAZIONE MAILBOX

# INDIRIZZO BASE
MAILBOX_BASE = 0x2007C000       # EQ A CTRL_REG

# HEADER GLOBALE: 16 BYTE
ADDR_DMA_INDEX          =   MAILBOX_BASE + 0x00         # SCRITTO DALL'IRQ HANDLER DEL DMA
ADDR_SELECTED_EFFECT    =   MAILBOX_BASE + 0x04         # ID DELL'EFFETTO ATTIVO PER IL DSP
ADDR_GLOBAL_VERSION     =   MAILBOX_BASE + 0x08         # VERSION COUNTER (NOTIFICA AL DSP SE SONO CAMBIATI PARAMETRI)
ADDR_VOLUME_TARGET      =   MAILBOX_BASE + 0x0C

# INDICI DELL'HEADER
DMA_INDEX = 0
EFFECT_INDEX = 1
VERSION_INDEX = 2

# BASI PER GLI EFFETTI
BYPASS_BASE = MAILBOX_BASE + 0x10
REVERB_BASE = MAILBOX_BASE + 0x30
DELAY_BASE = MAILBOX_BASE + 0x50


# INDICI DEGLI EFFETTI  (OGNI BLOCCO DELL'EFFETTO HA 8 WORD)
BYPASS_INDEX = 4
REVERB_INDEX = 12
DELAY_INDEX = 20

# OFFSET INTERNI AI SINGOLI BANCHI PER LEGGERE LA CONFIGURAZIONE ATTIVA E I PARAMETRI
ACTIVE_BANK_OFFSET = 0x00           # 0 = BANCO A, 1 = BANCO B
PARAMETER_1A_OFFSET = 0x04
PARAMETER_2A_OFFSET = 0x08
PARAMETER_1B_OFFSET = 0x0C
PARAMETER_2B_OFFSET = 0x10
# 3 PAROLE DI PADDING O PER PARAMETRI FUTURI

# INDICE DEI PARAMETRI (DA SOMMARE AGLI INDICI DEGLI EFFETTI)
ACTIVE_BANK_INDEX = 0
PARAMETER_1A_INDEX = 1
PARAMETER_2A_INDEX = 2
PARAMETER_1B_INDEX = 3
PARAMETER_2B_INDEX = 4

# DISTANZA TRA I BANCO A E IL BANCO B
BANK_STRIDE = 0x08

# NOTA: PAROLE TOTALI = 8*4 + 4 = 28
N_EFFECTS = 6
N_WORDS_MAILBOX = N_EFFECTS * 8 + 4

class Mailbox:

    # COSTRUTTORE DELLA CLASSE
    def __init__(self):
        self.version_counter = 0            # CONTATORE LOCALE DELLA VERSIONE

        # AZZERA LA MAILBOX IN RAM (IMPOSTA ANCHE LO STATO INIZIALE: BYPASS, DMA_INDEX = 0, GLOBAL_VERSION = 0)
        for i in range(N_WORDS_MAILBOX):
            machine.mem32[MAILBOX_BASE + (i*4)] = 0

        #machine.mem32[MAILBOX_BASE + ADDR_VOLUME_TARGET] = 0        # VALORE SENTINELLA, EVITA CHE IL MAIN VADA A VUOTO NELLE PRIME CHIAMATE

        # BARRIERA?     NON SERVE, LE SCRITTURE CON MACHINE MEM USANO UN PUNTATORE DI TIPO VOLATILE QUINDI LE ISTRUZIONI ASSOCIATE AD ESSO NON POSSONO ESSERE RIORDINATE
        #self.machine.dmb()

    def write(self, effect_id, p1_Q15, p2_Q15, change_effect):

        # DMA_INDEX NON CI RIGUARDA, È GESTITO DAL DMA!!

        # SCRIVE I PARAMETRI IN FORMATO Q15 NELLA MAILBOX, SE NECESSARIO CAMBIA ANCHE L'EFFETTO E ESEGUE LA SCRITTURA ATOMICAMENTE


        # CALCOLO LA BASE PER L'EFFETTO CORRENTE
        effect_base = BYPASS_BASE + (effect_id * 0x20)

        # RECUPERO LA CONFIGURAZIONE IN USO
        active_bank = machine.mem32[effect_base]

        # PREPARO LA CONFIGURAZIONE PASSIVA (SU CUI SCRIVERE)
        passive_bank = 1 - active_bank

        # SCRIVO IL PRIMO PARAMETRO
        machine.mem32[effect_base + PARAMETER_1A_OFFSET + passive_bank * BANK_STRIDE] = p1_Q15

        # SCRIVO IL SECONDO PARAMETRO
        machine.mem32[effect_base + PARAMETER_2A_OFFSET + passive_bank * BANK_STRIDE] = p2_Q15

        # SE DEVO SCRIVERE L'EFFETTO MODIFICO L'HEADER
        if change_effect:
            machine.mem32[ADDR_SELECTED_EFFECT] = effect_id

            #print("NUOVO EFFETTO:", effect_id)

        # MODIFICO LA CONFIGURAZIONE ATTIVA (OPERAZIONE ATOMICA)
        machine.mem32[effect_base] = passive_bank

        # AGGIORNO L'INDICE LOCALE
        self.version_counter += 1

        # AGGIORNO L'INDICE DELLA VERSIONE
        machine.mem32[ADDR_GLOBAL_VERSION] = self.version_counter

       

